"""Exact relation-product authority for real-cubic compact units.

The resident class-group path owns exact generators for every collected
principal relation.  To prove that a later reconstructed unit is the *same*
algebraic element generated by those relations, it must also retain the full
integer map from raw relation columns to the accepted unit-log columns.  This
module verifies that map when supplied and reports its exact missing shape
when it is absent.
"""

from __future__ import annotations

from dataclasses import dataclass
from math import gcd
from typing import Any, Sequence


class RelationUnitAuthorityFailure(ValueError):
    """Exact raw-relation correspondence is absent or inconsistent."""


@dataclass(frozen=True)
class MissingRelationMap:
    raw_relation_count: int
    accepted_column_count: int
    required_entries: int
    layout: str = "column-major-raw-relations-by-accepted-columns"


def required_relation_map(
    raw_relation_count: int,
    accepted_column_count: int,
    retained_map: Sequence[Any] | None,
) -> MissingRelationMap | None:
    """Return the exact missing authority boundary, or `None` when present."""
    if raw_relation_count < 1 or accepted_column_count < 1:
        raise RelationUnitAuthorityFailure("relation authority dimensions are invalid")
    required = raw_relation_count * accepted_column_count
    if retained_map is None:
        return MissingRelationMap(raw_relation_count, accepted_column_count, required)
    if isinstance(retained_map, (str, bytes)) or len(retained_map) != required:
        raise RelationUnitAuthorityFailure(
            f"raw-to-accepted relation map must contain exactly {required} entries"
        )
    return None


def _integers(values: Sequence[Any], length: int, name: str) -> list[int]:
    if isinstance(values, (str, bytes)) or len(values) != length:
        raise RelationUnitAuthorityFailure(name + " has the wrong bounded shape")
    return [int(value) for value in values]


def _multiply_cubic(
    left: Sequence[int], right: Sequence[int], tensor: Sequence[int]
) -> tuple[int, int, int]:
    matrix = [0] * 9
    for basis in range(3):
        for entry in range(9):
            matrix[entry] += left[basis] * tensor[9 * basis + entry]
    return tuple(
        sum(matrix[3 * column + row] * right[column] for column in range(3))
        for row in range(3)
    )


def _determinant3(matrix: Sequence[int]) -> int:
    return (
        matrix[0] * (matrix[4] * matrix[8] - matrix[7] * matrix[5])
        - matrix[3] * (matrix[1] * matrix[8] - matrix[7] * matrix[2])
        + matrix[6] * (matrix[1] * matrix[5] - matrix[4] * matrix[2])
    )


def _multiplication_matrix(element: Sequence[int], tensor: Sequence[int]) -> list[int]:
    return [
        sum(element[basis] * tensor[9 * basis + entry] for basis in range(3))
        for entry in range(9)
    ]


def _normalize(
    numerator: Sequence[int], denominator: int
) -> tuple[tuple[int, int, int], int]:
    if denominator == 0:
        raise RelationUnitAuthorityFailure("zero denominator in relation product")
    values = [int(value) for value in numerator]
    if denominator < 0:
        denominator = -denominator
        values = [-value for value in values]
    common = denominator
    for value in values:
        common = gcd(common, abs(value))
    if common > 1:
        denominator //= common
        values = [value // common for value in values]
    return (values[0], values[1], values[2]), denominator


def _rational_multiply(
    left: tuple[tuple[int, int, int], int],
    right: tuple[tuple[int, int, int], int],
    tensor: Sequence[int],
) -> tuple[tuple[int, int, int], int]:
    return _normalize(_multiply_cubic(left[0], right[0], tensor), left[1] * right[1])


def _rational_inverse(
    value: tuple[tuple[int, int, int], int], tensor: Sequence[int]
) -> tuple[tuple[int, int, int], int]:
    matrix = _multiplication_matrix(value[0], tensor)
    determinant = _determinant3(matrix)
    if determinant == 0:
        raise RelationUnitAuthorityFailure("zero relation generator is not invertible")
    # First column of the inverse multiplication matrix, in column-major form.
    adjugate = (
        matrix[4] * matrix[8] - matrix[7] * matrix[5],
        matrix[2] * matrix[7] - matrix[1] * matrix[8],
        matrix[1] * matrix[5] - matrix[2] * matrix[4],
    )
    return _normalize(
        tuple(value[1] * coordinate for coordinate in adjugate), determinant
    )


def _rational_power(
    element: Sequence[int], exponent: int, tensor: Sequence[int]
) -> tuple[tuple[int, int, int], int]:
    base = ((int(element[0]), int(element[1]), int(element[2])), 1)
    if exponent < 0:
        base = _rational_inverse(base, tensor)
        exponent = -exponent
    answer = ((1, 0, 0), 1)
    while exponent:
        if exponent & 1:
            answer = _rational_multiply(answer, base, tensor)
        exponent >>= 1
        if exponent:
            base = _rational_multiply(base, base, tensor)
    return answer


def verify_cubic_relation_units(
    raw_generators: Sequence[Any],
    raw_relation_count: int,
    raw_to_accepted: Sequence[Any],
    accepted_column_count: int,
    unit_exponents: Sequence[Any],
    target_units: Sequence[Any],
    multiplication_tensor: Sequence[Any],
) -> dict[str, Any]:
    """Replay raw principal generators through both retained integer maps.

    `raw_to_accepted` is column-major with shape
    `raw_relation_count x accepted_column_count`. `unit_exponents` is
    row-major with one row per target unit. Negative raw exponents are handled
    as exact rational field elements; every accepted factor and final target
    must normalize back to an integral unit.
    """
    if (
        required_relation_map(
            raw_relation_count, accepted_column_count, raw_to_accepted
        )
        is not None
    ):
        raise RelationUnitAuthorityFailure("raw relation map is absent")
    generators = _integers(
        raw_generators, 3 * raw_relation_count, "raw relation generators"
    )
    transform = _integers(
        raw_to_accepted,
        raw_relation_count * accepted_column_count,
        "raw-to-accepted relation map",
    )
    tensor = _integers(multiplication_tensor, 27, "cubic multiplication tensor")
    targets = [int(value) for value in target_units]
    if len(targets) == 0 or len(targets) % 3:
        raise RelationUnitAuthorityFailure("target units have the wrong shape")
    rank = len(targets) // 3
    exponents = _integers(
        unit_exponents,
        rank * accepted_column_count,
        "accepted-column unit exponents",
    )
    factors: list[tuple[int, int, int]] = []
    factor_norms: list[int] = []
    for column in range(accepted_column_count):
        value = ((1, 0, 0), 1)
        for relation in range(raw_relation_count):
            exponent = transform[column * raw_relation_count + relation]
            if exponent:
                generator = generators[3 * relation : 3 * relation + 3]
                value = _rational_multiply(
                    value, _rational_power(generator, exponent, tensor), tensor
                )
        if value[1] != 1:
            raise RelationUnitAuthorityFailure(
                "accepted relation product is not an integral element"
            )
        norm = _determinant3(_multiplication_matrix(value[0], tensor))
        if norm not in (-1, 1):
            raise RelationUnitAuthorityFailure(
                "accepted relation product is not an algebraic unit"
            )
        factors.append(value[0])
        factor_norms.append(norm)
    actual: list[tuple[int, int, int]] = []
    for unit in range(rank):
        value = ((1, 0, 0), 1)
        for factor in range(accepted_column_count):
            exponent = exponents[unit * accepted_column_count + factor]
            if exponent:
                value = _rational_multiply(
                    value, _rational_power(factors[factor], exponent, tensor), tensor
                )
        wanted = tuple(targets[3 * unit : 3 * unit + 3])
        if value != (wanted, 1):
            raise RelationUnitAuthorityFailure(
                f"relation product does not equal reconstructed unit {unit}"
            )
        actual.append(value[0])
    return {
        "raw_relation_count": raw_relation_count,
        "accepted_column_count": accepted_column_count,
        "rank": rank,
        "factor_norms": factor_norms,
        "units": actual,
        "correspondence": "exact-raw-relation-product",
    }


__all__ = [
    "MissingRelationMap",
    "RelationUnitAuthorityFailure",
    "required_relation_map",
    "verify_cubic_relation_units",
]

"use strict";

const { mkdtempSync, rmSync, writeFileSync } = require("node:fs");
const { tmpdir } = require("node:os");
const { join, resolve } = require("node:path");
const { spawnSync } = require("node:child_process");
const { compile } = require("../tools/native-kernel.cjs");

const root = resolve(__dirname, "..");
const sourcePath = join(__dirname, "native_tate_large_prime.py");
const cacheRoot = process.env.SAGEJS_NATIVE_TATE_CACHE ||
  join(tmpdir(), "sagejs-native-tate-benchmark");
const repetitions = Number(process.env.SAGEJS_NATIVE_TATE_REPETITIONS || 10000);

// The expected triples were generated by PARI 2.17.3 elllocalred.  Together
// they cover good, multiplicative, II/III/IV, I0*, IV*/III*/II*, and several
// multiplicative I_n branches at primes greater than three.
const cases = [
  [[0, 0, 1, -1, 0], 5, [0n, 1n, 1n]],
  [[0, 0, 0, 0, 5], 5, [2n, 2n, 1n]],
  [[0, 0, 0, 0, 25], 5, [2n, 4n, 3n]],
  [[0, 0, 0, 0, 125], 5, [2n, -1n, 2n]],
  [[0, 0, 0, 0, 625], 5, [2n, -4n, 3n]],
  [[0, 0, 0, 0, 3125], 5, [2n, -2n, 1n]],
  [[0, 0, 0, 5, 0], 5, [2n, 3n, 2n]],
  [[0, 0, 0, 25, 0], 5, [2n, -1n, 4n]],
  [[0, 0, 0, 125, 0], 5, [2n, -3n, 2n]],
  [[0, -1, 1, -10, -20], 11, [1n, 9n, 5n]],
  [[1, -16, 0, -9, 16], 11, [1n, 5n, 1n]],
  [[7, 1, 17, 16, 0], 17, [1n, 6n, 2n]],
  [[3, 20, -4, -7, -10], 13, [1n, 7n, 1n]],
];

function equal(left, right) {
  return left.length === right.length &&
    left.every((value, index) => value === right[index]);
}

function median(values) {
  const ordered = [...values].sort((left, right) => left - right);
  return ordered[Math.floor(ordered.length / 2)];
}

function measure(fn) {
  for (let warmup = 0; warmup < 100; warmup += 1) {
    for (const [coefficients, prime] of cases) fn(...coefficients, prime);
  }
  const samples = [];
  let witness;
  for (let sample = 0; sample < 9; sample += 1) {
    const start = process.hrtime.bigint();
    for (let iteration = 0; iteration < repetitions; iteration += 1) {
      for (const [coefficients, prime] of cases) {
        witness = fn(...coefficients, prime);
      }
    }
    samples.push(
      Number(process.hrtime.bigint() - start) / (repetitions * cases.length),
    );
  }
  if (witness === undefined) throw new Error("benchmark produced no result");
  return median(samples);
}

function pariComparison() {
  const check = cases.map(([coefficients, prime]) =>
    `E=ellinit([${coefficients.join(",")}]);` +
    `r=elllocalred(E,${prime});print([r[1],r[2],r[4]])`
  ).join(";");
  const timed = "E=ellinit([0,-1,1,-10,-20]);" +
    `N=${Math.max(100000, repetitions)};gettime();` +
    "for(i=1,N,elllocalred(E,11));" +
    'print("TIME=",gettime())';
  const result = spawnSync("gp", ["-fq"], {
    input: `${check};${timed}\n`,
    encoding: "utf8",
  });
  if (result.error?.code === "ENOENT") return null;
  if (result.status !== 0) throw new Error(result.stderr || result.stdout);
  const lines = result.stdout.trim().split("\n");
  for (let index = 0; index < cases.length; index += 1) {
    const actual = JSON.parse(lines[index]).map(BigInt);
    if (!equal(actual, cases[index][2])) {
      throw new Error(`PARI disagrees on Tate corpus case ${index}`);
    }
  }
  const elapsed = Number(lines.find((line) => line.startsWith("TIME=")).slice(5));
  return elapsed * 1e6 / Math.max(100000, repetitions);
}

function productionSagejsComparison() {
  const temporary = mkdtempSync(join(tmpdir(), "sagejs-tate-production-"));
  const path = join(temporary, "benchmark.py");
  const plainCases = cases.map(([coefficients, prime]) => [coefficients, prime]);
  const iterations = Math.max(1000, Math.floor(repetitions / 10));
  writeFileSync(path, `from time import perf_counter
import sagejs_elliptic_advanced as advanced
import sagejs.runtime as runtime
cases = ${JSON.stringify(plainCases)}
cases = [([runtime.bigint(value) for value in coefficients], prime)
         for coefficients, prime in cases]
for _ in range(100):
    for coefficients, prime in cases:
        advanced._ec_tate_local_data(coefficients, prime)
start = perf_counter()
for _ in range(${iterations}):
    for coefficients, prime in cases:
        advanced._ec_tate_local_data(coefficients, prime)
print((perf_counter() - start) * 1e9 / (${iterations} * len(cases)))
`);
  try {
    const result = spawnSync(process.execPath, [join(root, "bin", "sagejs"), path], {
      cwd: root,
      encoding: "utf8",
      env: { ...process.env, SAGEJS_NATIVE_AUTOLOAD: "0" },
    });
    if (result.status !== 0) return { error: result.stderr.trim() };
    return { nanoseconds: Number(result.stdout.trim()) };
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

(async () => {
  const result = await compile({
    sourcePath,
    functions: ["tate_large_prime"],
    cacheRoot,
  });
  const kernel = require(result.modulePath);
  const fn = kernel.tate_large_prime;
  const implementations = {
    selected: fn,
    javascript: fn.javascript,
    tagged: fn.tagged,
    gmp: fn.gmp,
  };
  for (const [name, implementation] of Object.entries(implementations)) {
    for (const [coefficients, prime, expected] of cases) {
      const actual = implementation(...coefficients, prime);
      if (!equal(actual, expected)) {
        throw new Error(`${name} disagrees with PARI corpus`);
      }
    }
  }

  console.log("Tate local reduction at p > 3 (warm ns/case)");
  for (const [name, implementation] of Object.entries(implementations)) {
    console.log(`${name.padEnd(18)} ${measure(implementation).toFixed(1)}`);
  }
  const production = productionSagejsComparison();
  if (production.nanoseconds !== undefined) {
    console.log(`${"Sage.js Python".padEnd(18)} ${production.nanoseconds.toFixed(1)}`);
  } else {
    console.log(`Sage.js Python unavailable: ${production.error}`);
  }
  const pari = pariComparison();
  console.log(pari === null
    ? "PARI/GP unavailable"
    : `${"PARI/GP".padEnd(18)} ${pari.toFixed(1)}`);
  console.log(`cases=${cases.length} repetitions=${repetitions}`);
})().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});

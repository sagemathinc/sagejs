#!/usr/bin/env node
"use strict";

// Focused public benchmark and implementation contract for exact polynomial
// ingress.  This deliberately does not mutate the production implementation:
// it identifies the current transport costs and freezes the requirements for
// the later shared-FFI implementation lane.

const assert = require("node:assert/strict");
const { execFileSync, spawnSync } = require("node:child_process");
const { mkdtempSync, readFileSync, rmSync, writeFileSync } = require("node:fs");
const { tmpdir } = require("node:os");
const { join, resolve } = require("node:path");
const { performance } = require("node:perf_hooks");

const root = resolve(__dirname, "..");
const sagejs = join(root, "bin", "sagejs");

function argument(name, fallback = undefined) {
  const index = process.argv.indexOf(name);
  return index < 0 ? fallback : process.argv[index + 1];
}

if (process.argv.includes("--help") || process.argv.includes("-h")) {
  process.stdout.write(`Usage: node bench/exact-polynomial-bulk-construction-contract.cjs [options]

  --runtime VALUE   sagejs, sage, or all (default: sagejs)
  --sage PATH       SageMath executable required by sage/all
  --samples N       Warm samples per operation (default: 7)
  --count N         Coefficient count (default: 5001)
  --output PATH     Write the complete JSON report
  --evidence LABEL=PATH
                    Attach a previously recorded host report; repeatable
  --check           Check execution, summaries, and cross-runtime semantics

The benchmark records process wall time, raw-input setup, the first public
construction after setup, and a same-process warm median separately. Sage.js
also reports diagnostic transport stages. Stage timings are not additive and
are not cross-runtime performance claims.
`);
  process.exit(0);
}

const samples = Number(argument("--samples", "7"));
const count = Number(argument("--count", "5001"));
const requestedRuntime = argument("--runtime", "sagejs");
const sage = argument("--sage", process.env.SAGEJS_BENCH_SAGE);
const output = argument("--output");
const check = process.argv.includes("--check");
const evidenceArguments = process.argv.flatMap((value, index, values) =>
  value === "--evidence" && values[index + 1] ? [values[index + 1]] : []
);

assert.ok(Number.isInteger(samples) && samples >= 3 && samples <= 31);
assert.ok(Number.isInteger(count) && count >= 1 && count <= 1_000_001);
assert.ok(["sagejs", "sage", "all"].includes(requestedRuntime));
if ((requestedRuntime === "sage" || requestedRuntime === "all") && !sage) {
  throw new Error("--runtime sage/all requires --sage PATH");
}

const implementationContract = Object.freeze({
  schema: "sagejs.contract/exact-polynomial-bulk-construction-v1",
  scope: ["ZZ[x] public dense construction", "QQ[x] public dense construction"],
  eliminated_bottleneck: {
    path: [
      "coerce and normalize every host coefficient",
      "encode variable-size signed magnitudes as canonical SJPZ/SJPQ bytes",
      "copy the stream into a host Buffer",
      "reverse and hexadecimal-encode the complete stream",
      "parse one stream-sized host BigInt",
      "marshal that BigInt as fmpz across generated FFI",
      "reconstruct the bytes and deserialize into FLINT",
    ],
    diagnosis:
      "The former bulk path unnecessarily round-tripped its canonical byte stream through one enormous exact integer. Production now packs a checked host list once and parses one borrowed FlintByteRegion directly.",
  },
  required_api: [
    {
      declaration: "flint:fmpz_polynomial_from_byte_region",
      arguments: ["FlintByteRegion source", "uint64 offset", "uint64 length"],
      result: "owned sealed FmpzPolynomial",
    },
    {
      declaration: "flint:fmpq_polynomial_from_byte_region",
      arguments: ["FlintByteRegion source", "uint64 offset", "uint64 length"],
      result: "owned sealed FmpqPolynomial",
    },
  ],
  lowering: {
    ingress:
      "Encode canonical SJPZ/SJPQ bytes once, create one generated owned FlintByteRegion with one host-to-foreign copy, borrow it synchronously while parsing, and close it in finally.",
    host_fast_path:
      "For an exact list, feed ZZ values directly to exact_integer_values_to_packed_bytes and canonical QQ values directly to canonical_rational_values_to_packed_bytes. Fall back to the ordinary coercion loop only when the checked primitive declines the input.",
    ownership:
      "The returned polynomial is independent of the temporary byte region; validation failure publishes no resource and leaks neither owner.",
    node:
      "Use the generated byte-region from-bytes adapter; no handwritten operation-specific N-API and no stream-sized BigInt transport.",
    wasm:
      "Copy the canonical stream into linear/owned foreign memory, borrow it for the same parser, and preserve the packed dynamic fallback when FLINT resources are unavailable.",
  },
  invariants: [
    "ordinary CPython-parseable public Python remains the source of construction semantics",
    "trailing zero coefficients are removed and all zero inputs produce the unique zero polynomial",
    "QQ coefficients are normalized with positive coprime denominators before publication",
    "arbitrarily skewed coefficient sizes require no uniform per-entry limb capacity",
    "one public construction performs no coefficient-at-a-time foreign calls",
    "already-canonical host lists do not allocate a second Python list of scalar parts",
    "one public construction performs at most one host-to-foreign byte-stream copy on Node",
    "FLINT-to-FLINT polynomial operations never serialize through this ingress format",
    "the canonical SJPZ/SJPQ wire format and SagePack round trips remain unchanged",
    "invalid or unrepresentable streams fail transactionally with deterministic cleanup",
  ],
  semantic_differentials: [
    "empty and all-zero inputs",
    "list and tuple inputs",
    "trailing zeros",
    "negative and machine-word coefficients",
    "one highly skewed 65538-bit coefficient among small coefficients",
    "canonical rational signs, zeros, and large relatively-prime denominators",
    "degree, selected coefficient access, equality, and SagePack round trip",
    "invalid coefficient coercion leaves no partially published resource",
    "generated-resource capability disabled uses the correct packed fallback",
  ],
  acceptance: {
    correctness:
      "All semantic differentials agree between generated-resource execution, capability-disabled packed execution, and SageMath where formats are comparable.",
    boundary:
      "Generated adapter audit proves one checked host-list packing operation, one byte-region creation, one borrowed parse, zero scalar coefficient calls, and no stream-sized BigInt.",
    performance:
      "On each measured host, report fresh-process setup, first invocation, and a warm median separately, including a same-host SageMath ratio whenever a usable SageMath oracle is installed. Test 5001 and 20001 coefficients plus skewed inputs for linear scaling in coefficient count and encoded bytes; record generated-copy and borrowed-parse costs without turning one host's timing into a universal acceptance constant.",
    remaining_performance_goal:
      "The originally proposed public warm-construction target of at most 2x same-host SageMath remains unmet, especially for QQ[x]. It is an explicit follow-up optimization goal rather than being silently weakened or misreported as an FFI correctness gate.",
    portability:
      "Linux x64 and macOS arm64 must exercise the generated resource; Windows x64 and Wasm require either that path or a tested correct capability fallback.",
    maintainability:
      "The implementation adds declarations and ordinary Python wiring but no compiler branch specific to polynomial construction.",
    stage_gates: {
      canonical_pack:
        "The benchmark must time the checked direct host-list pack separately for ZZ and QQ, and a route/audit test must prove that public canonical-list construction actually uses it rather than merely leaving the primitive available.",
      byte_region:
        "The current benchmark records ByteRegion creation as a baseline-only stage. Once the required parser API exists, it must time region creation and the borrowed FLINT parse separately; audit must reject Buffer reverse/hex, stream-sized BigInt, and fmpz payload marshalling in the public constructor.",
      end_to_end:
        "The same benchmark must retain public first and warm measurements. Passing only the ByteRegion stage or only the canonical-pack stage is insufficient: both route assertions and the end-to-end same-host SageMath ratio must pass.",
      skew:
        "Run the public path with one 65538-bit value among small values and report encoded bytes; time and memory must scale with total encoded bytes, not maximum limb size times coefficient count.",
    },
  },
});

function commandOutput(command, args) {
  try {
    return execFileSync(command, args, { encoding: "utf8" }).trim();
  } catch {
    return null;
  }
}

function publicSource(domain) {
  const raw = domain === "ZZ"
    ? `[((1103515245 * (i + 102) + 12345) % 2001) - 1000 for i in range(${count})]`
    : `[QQ(((1103515245 * (i + 102) + 12345) % 2001) - 1000) / QQ(((i + 303) % 31) + 1) for i in range(${count})]`;
  return `
import json
import time

started = time.perf_counter()
R = PolynomialRing(${domain}, "x")
raw = ${raw}
setup_ms = 1000 * (time.perf_counter() - started)

started = time.perf_counter()
answer = R(raw)
first_ms = 1000 * (time.perf_counter() - started)
first_summary = [int(answer.degree()), str(answer[0]), str(answer[${count - 1}]), str(answer[${Math.floor(count / 2)}])]

R(raw)
R(raw)
timings = []
for repeat in range(${samples}):
    started = time.perf_counter()
    answer = R(raw)
    timings.append(1000 * (time.perf_counter() - started))
timings.sort()
summary = [int(answer.degree()), str(answer[0]), str(answer[${count - 1}]), str(answer[${Math.floor(count / 2)}])]
print("SAGEJS_EXACT_POLY " + json.dumps({"setup_ms": setup_ms, "first_ms": first_ms, "warm_ms": timings[len(timings) // 2], "first_delta_ms": first_ms - timings[len(timings) // 2], "summary": summary, "first_summary_matches": first_summary == summary}, separators=(",", ":")))
`;
}

function stageSource(domain) {
  const rational = domain === "QQ";
  const raw = rational
    ? `[QQ(((1103515245 * (i + 102) + 12345) % 2001) - 1000) / QQ(((i + 303) % 31) + 1) for i in range(${count})]`
    : `[((1103515245 * (i + 102) + 12345) % 2001) - 1000 for i in range(${count})]`;
  return `
import json
import time
import sagejs.runtime as runtime
import sagejs as sage
import sagejs._baselib.polynomial as internal

raw = ${raw}
ffi = internal._flint_ffi_module()
R = PolynomialRing(${domain}, "x")
huge = 2**65537 + 1
${rational
  ? `large_denominator = 2**32771 + 1
skew = [QQ(1) for index in range(${count})]
skew[len(skew) // 2] = QQ(huge) / QQ(large_denominator)`
  : `skew = [1 for index in range(${count})]
skew[len(skew) // 2] = huge`}

def median_call(function):
    function()
    function()
    timings = []
    for repeat in range(${samples}):
        started = time.perf_counter()
        function()
        timings.append(1000 * (time.perf_counter() - started))
    timings.sort()
    return timings[len(timings) // 2]

def fast_pack_body():
    ${rational
      ? "return runtime.canonical_rational_values_to_packed_bytes(raw, sage.Rational, sage.QQ)"
      : "return runtime.exact_integer_values_to_packed_bytes(raw)"}

def skew_fast_pack_body():
    ${rational
      ? "return runtime.canonical_rational_values_to_packed_bytes(skew, sage.Rational, sage.QQ)"
      : "return runtime.exact_integer_values_to_packed_bytes(skew)"}

def skew_public_construct():
    answer = R(skew)
    ${rational
      ? "if answer[len(skew) // 2] != QQ(huge) / QQ(large_denominator):\n        raise AssertionError(\"skewed rational coefficient changed\")"
      : "if answer[len(skew) // 2] != huge:\n        raise AssertionError(\"skewed integer coefficient changed\")"}
    answer._exact_polynomial_resource().close()

body = fast_pack_body()
envelope = internal._exact_polynomial_bytes(body, ${count}, ${rational ? "True" : "False"})

def parse_byte_region():
    resource = internal._exact_polynomial_resource_from_bytes(
        envelope, ${rational ? "True" : "False"}
    )
    resource.close()

def create_byte_region():
    copied = ffi.FlintByteRegion.from_bytes(envelope)
    copied.close()

report = {
    "checked_host_list_pack_ms": median_call(fast_pack_body),
    "canonical_envelope_ms": median_call(lambda: internal._exact_polynomial_bytes(body, ${count}, ${rational ? "True" : "False"})),
    "byte_region_creation_ms": median_call(create_byte_region),
    "borrowed_parse_ms": median_call(parse_byte_region),
    "encoded_bytes": len(envelope),
    "skew_checked_host_list_pack_ms": median_call(skew_fast_pack_body),
    "skew_public_construct_ms": median_call(skew_public_construct),
    "skew_encoded_bytes": len(skew_fast_pack_body()) + 16,
    "skew_bits": 65538,
}
print("SAGEJS_EXACT_POLY_STAGE " + json.dumps(report, separators=(",", ":")))
`;
}

function runSource(runtime, executable, source, directory, name) {
  const path = join(directory, `${runtime}-${name}.sage`);
  writeFileSync(path, source);
  const started = performance.now();
  const result = spawnSync(
    runtime === "sagejs" ? process.execPath : executable,
    runtime === "sagejs" ? [sagejs, path] : [path],
    {
      cwd: root,
      encoding: "utf8",
      timeout: 10 * 60_000,
      maxBuffer: 16 * 1024 * 1024,
      env: {
        ...process.env,
        OPENBLAS_NUM_THREADS: "1",
        OMP_NUM_THREADS: "1",
        VECLIB_MAXIMUM_THREADS: "1",
        SAGEJS_FORBID_POLYNOMIAL_NAPI: runtime === "sagejs" ? "1" : process.env.SAGEJS_FORBID_POLYNOMIAL_NAPI,
      },
    },
  );
  const processMs = performance.now() - started;
  if (result.error || result.status !== 0) {
    return {
      ok: false,
      process_ms: processMs,
      error: String(result.error || result.stderr || result.stdout).slice(0, 4000),
    };
  }
  return { ok: true, process_ms: processMs, stdout: result.stdout };
}

function parseSentinel(run, sentinel) {
  if (!run.ok) return run;
  const line = run.stdout
    .split("\n")
    .find((candidate) => candidate.startsWith(sentinel));
  if (!line) {
    return { ok: false, process_ms: run.process_ms, error: `missing ${sentinel}: ${run.stdout.slice(-2000)}` };
  }
  return { ok: true, process_ms: run.process_ms, ...JSON.parse(line.slice(sentinel.length)) };
}

const runtimes = requestedRuntime === "all"
  ? [["sagejs", sagejs], ["sage", sage]]
  : requestedRuntime === "sage"
    ? [["sage", sage]]
    : [["sagejs", sagejs]];
const directory = mkdtempSync(join(tmpdir(), "sagejs-exact-poly-contract-"));
const measurements = {};
const stages = {};
try {
  for (const [runtime, executable] of runtimes) {
    measurements[runtime] = {};
    for (const domain of ["ZZ", "QQ"]) {
      const parsed = parseSentinel(
        runSource(runtime, executable, publicSource(domain), directory, `${domain}-public`),
        "SAGEJS_EXACT_POLY ",
      );
      measurements[runtime][domain] = parsed;
      process.stderr.write(`${runtime.padEnd(6)} ${domain}[x] construct ${parsed.ok ? parsed.warm_ms.toFixed(3) : "FAILED"} ms\n`);
      if (runtime === "sagejs") {
        stages[domain] = parseSentinel(
          runSource(runtime, executable, stageSource(domain), directory, `${domain}-stages`),
          "SAGEJS_EXACT_POLY_STAGE ",
        );
      }
    }
  }
} finally {
  rmSync(directory, { recursive: true, force: true });
}

const comparisons = {};
if (measurements.sagejs && measurements.sage) {
  for (const domain of ["ZZ", "QQ"]) {
    const local = measurements.sagejs[domain];
    const oracle = measurements.sage[domain];
    comparisons[domain] = {
      summaries_match: local.ok && oracle.ok
        ? JSON.stringify(local.summary) === JSON.stringify(oracle.summary)
        : null,
      sagejs_over_sage: local.ok && oracle.ok ? local.warm_ms / oracle.warm_ms : null,
    };
  }
}

const report = {
  schema: "sagejs.benchmark/exact-polynomial-bulk-construction-v1",
  generated_at: new Date().toISOString(),
  host: {
    platform: process.platform,
    architecture: process.arch,
    uname: commandOutput("uname", ["-a"]),
    cpu: process.platform === "darwin"
      ? commandOutput("sysctl", ["-n", "machdep.cpu.brand_string"])
      : readFileSync("/proc/cpuinfo", "utf8").match(/^model name\s*:\s*(.*)$/m)?.[1] || null,
  },
  repository: {
    commit: commandOutput("git", ["rev-parse", "HEAD"]),
    branch: commandOutput("git", ["branch", "--show-current"]),
    dirty: commandOutput("git", ["status", "--porcelain"]) !== "",
  },
  configuration: {
    count,
    samples,
    timing: "fresh process per domain; setup, first invocation, warm median, and complete process wall time reported separately",
    threads: 1,
  },
  contract: implementationContract,
  runtimes: Object.fromEntries(runtimes.map(([runtime, executable]) => [runtime, {
    executable,
    version: runtime === "sagejs"
      ? require(join(root, "package.json")).version
      : commandOutput(executable, ["--version"]),
  }])),
  measurements,
  diagnostic_stages: stages,
  comparisons,
  additional_host_evidence: evidenceArguments.map((entry) => {
    const separator = entry.indexOf("=");
    assert.ok(separator > 0, "--evidence must be LABEL=PATH");
    const label = entry.slice(0, separator);
    const source = JSON.parse(readFileSync(resolve(entry.slice(separator + 1)), "utf8"));
    assert.equal(source.schema, "sagejs.benchmark/exact-polynomial-bulk-construction-v1");
    return {
      label,
      generated_at: source.generated_at,
      host: source.host,
      repository: source.repository,
      configuration: source.configuration,
      runtimes: source.runtimes,
      measurements: source.measurements,
      diagnostic_stages: source.diagnostic_stages,
      comparisons: source.comparisons,
    };
  }),
};

if (check) {
  for (const [runtime, domains] of Object.entries(measurements)) {
    for (const domain of ["ZZ", "QQ"]) {
      assert.equal(domains[domain].ok, true, `${runtime} ${domain} failed: ${domains[domain].error}`);
      assert.equal(domains[domain].first_summary_matches, true, `${runtime} ${domain} first/warm summaries differ`);
    }
  }
  for (const domain of ["ZZ", "QQ"]) {
    if (measurements.sagejs) {
      assert.equal(stages[domain].ok, true, `Sage.js ${domain} stage diagnosis failed`);
      assert.ok(stages[domain].encoded_bytes > 16, `${domain} encoded no coefficients`);
    }
    if (measurements.sagejs && measurements.sage) {
      assert.equal(comparisons[domain].summaries_match, true, `${domain} differs from SageMath`);
    }
  }
}

const encoded = `${JSON.stringify(report, null, 2)}\n`;
if (output) writeFileSync(resolve(output), encoded);
process.stdout.write(encoded);

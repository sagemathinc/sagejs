"""Certified rational-prime decomposition in maximal number-field orders.

The producer has two exact routes.  Dedekind--Kummer is used only after the
integral equation order is proved `p`-maximal.  Every other supported case is
handled in the presentation-independent finite algebra `O/pO`: its
nilradical is the kernel of a sufficiently high Frobenius power, the reduced
quotient is generated by a bounded deterministic primitive-element search,
and its irreducible factors lift to exact HNF ideal lattices.

Both routes feed :func:`verify_prime_decomposition`, which only consumes the
returned lattices and compact residue presentations.  In particular, producer
branch metadata is never accepted as a proof of its own output.
"""


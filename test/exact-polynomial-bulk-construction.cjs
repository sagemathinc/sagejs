#!/usr/bin/env node
"use strict";

const assert = require("node:assert/strict");
const { mkdtempSync, rmSync, writeFileSync } = require("node:fs");
const { tmpdir } = require("node:os");
const { join, resolve } = require("node:path");
const { spawnSync } = require("node:child_process");
const test = require("node:test");

const root = resolve(__dirname, "..");

function runSage(source, environment = {}) {
  const directory = mkdtempSync(join(tmpdir(), "sagejs-exact-poly-ingress-"));
  try {
    const script = join(directory, "check.py");
    writeFileSync(script, source);
    const result = spawnSync(process.execPath, [join(root, "bin/sagejs"), script], {
      cwd: root,
      encoding: "utf8",
      timeout: 180_000,
      env: { ...process.env, SAGEJS_FORBID_POLYNOMIAL_NAPI: "1", ...environment },
    });
    assert.equal(result.status, 0, `${result.stdout}\n${result.stderr}`);
    return result.stdout.trim();
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

const publicConstruction = String.raw`
import sagejs.runtime as runtime
import sagejs.ffi.flint as ffi
import sagejs._baselib.polynomial as polynomial_module
from sagejs_serialization import dumps, loads

original_integer_pack = runtime.exact_integer_values_to_packed_bytes
original_rational_pack = runtime.canonical_rational_values_to_packed_bytes
original_from_bytes = ffi.FlintByteRegion.from_bytes
original_z_parse = ffi.fmpz_polynomial_from_byte_region
original_q_parse = ffi.fmpq_polynomial_from_byte_region

events = []
regions = []

def tracked_integer_pack(values):
    events.append('pack-z')
    return original_integer_pack(values)

def tracked_rational_pack(values, rational_class, parent):
    events.append('pack-q')
    return original_rational_pack(values, rational_class, parent)

def tracked_from_bytes(source):
    events.append('region')
    region = original_from_bytes(source)
    regions.append(region)
    return region

def tracked_z_parse(region, offset, length):
    events.append('parse-z')
    return original_z_parse(region, offset, length)

def tracked_q_parse(region, offset, length):
    events.append('parse-q')
    return original_q_parse(region, offset, length)

runtime.exact_integer_values_to_packed_bytes = tracked_integer_pack
runtime.canonical_rational_values_to_packed_bytes = tracked_rational_pack
ffi.FlintByteRegion.from_bytes = tracked_from_bytes
ffi.fmpz_polynomial_from_byte_region = tracked_z_parse
ffi.fmpq_polynomial_from_byte_region = tracked_q_parse

def forbidden(*args):
    raise AssertionError('legacy stream-sized integer or scalar ingress was used')

ffi.fmpz_polynomial_deserialize = forbidden
ffi.fmpq_polynomial_deserialize = forbidden
ffi.fmpz_polynomial_set_coefficient = forbidden
ffi.fmpq_polynomial_set_coefficient = forbidden

R = PolynomialRing(ZZ, 'x')
S = PolynomialRing(QQ, 'y')
huge = 2**65537 + 17
denominator = 2**32771 + 1
zvalues = [1, -2, 0, huge, -huge, 7, 0, 0]
qvalues = [QQ(1, 2), QQ(-2, 3), 0, QQ(huge, denominator), QQ(-5, huge), 7, 0]

events.clear()
z = R(zvalues)
assert events == ['pack-z', 'region', 'parse-z']
assert z.coefficients() == zvalues[:-2]
assert all(region.closed for region in regions)
zvalues[0] = 999
assert z[0] == 1

events.clear()
q = S(qvalues)
assert events == ['pack-q', 'region', 'parse-q']
assert q.coefficients() == qvalues[:-1]
assert all(region.closed for region in regions)
qvalues[0] = 99
assert q[0] == QQ(1, 2)

# The first pack declines arbitrary values and the ordinary Sage coercion loop
# remains observable and correct before the canonical retry.
class Coercible:
    def __init__(self, value):
        self.value = value
    def __int__(self):
        return self.value

events.clear()
coerced = R([Coercible(3), Coercible(-4)])
assert coerced == R([3, -4])
assert events[:2] == ['pack-z', 'pack-z']

assert loads(dumps(z)) == z
assert loads(dumps(q)) == q
assert all(region.closed for region in regions)
print('exact-polynomial-bulk-construction-ok')
`;

test("public exact polynomial construction selects one generated byte-region parse", () => {
  assert.equal(runSage(publicConstruction), "exact-polynomial-bulk-construction-ok");
});

const portableConstruction = String.raw`
import sagejs._baselib.polynomial as polynomial_module
polynomial_module._generated_flint_resources_available_cache = False
R = PolynomialRing(ZZ, 'x')
S = PolynomialRing(QQ, 'y')
huge = 2**65537 + 17
denominator = 2**32771 + 1
z = R([1, -2, huge, 0])
q = S([QQ(-1, 2), QQ(huge, denominator), 0])
assert z.coefficients() == [1, -2, huge]
assert q.coefficients() == [QQ(-1, 2), QQ(huge, denominator)]
assert not z._has_fmpz_polynomial_resource()
assert not q._has_fmpq_polynomial_resource()
print('exact-polynomial-portable-construction-ok')
`;

test("capability-disabled construction preserves packed exact semantics", () => {
  assert.equal(
    runSage(portableConstruction, { SAGEJS_NATIVE_DISABLE: "1" }),
    "exact-polynomial-portable-construction-ok",
  );
});

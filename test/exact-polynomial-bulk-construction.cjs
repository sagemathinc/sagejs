#!/usr/bin/env node
"use strict";

const assert = require("node:assert/strict");
const { mkdtempSync, readFileSync, rmSync, writeFileSync } = require("node:fs");
const { tmpdir } = require("node:os");
const { join, resolve } = require("node:path");
const { spawnSync } = require("node:child_process");
const test = require("node:test");

const root = resolve(__dirname, "..");

function runSage(source, environment = {}) {
  const directory = mkdtempSync(join(tmpdir(), "sagejs-exact-poly-ingress-"));
  try {
    const script = join(directory, "check.py");
    writeFileSync(script, source);
    const result = spawnSync(process.execPath, [join(root, "bin/sagejs"), script], {
      cwd: root,
      encoding: "utf8",
      timeout: 180_000,
      env: { ...process.env, SAGEJS_FORBID_POLYNOMIAL_NAPI: "1", ...environment },
    });
    assert.equal(result.status, 0, `${result.stdout}\n${result.stderr}`);
    return result.stdout.trim();
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

const publicConstruction = String.raw`
import sagejs.ffi.flint as ffi
import sagejs._baselib.polynomial as polynomial_module
from sagejs_serialization import dumps, loads

original_from_bytes = ffi.FlintByteRegion.from_bytes
original_z_parse = ffi.fmpz_polynomial_from_byte_region
original_q_parse = ffi.fmpq_polynomial_from_byte_region

events = []
regions = []

def tracked_from_bytes(source):
    events.append('region')
    region = original_from_bytes(source)
    regions.append(region)
    return region

def tracked_z_parse(region, offset, length):
    events.append('parse-z')
    return original_z_parse(region, offset, length)

def tracked_q_parse(region, offset, length):
    events.append('parse-q')
    return original_q_parse(region, offset, length)

ffi.FlintByteRegion.from_bytes = tracked_from_bytes
ffi.fmpz_polynomial_from_byte_region = tracked_z_parse
ffi.fmpq_polynomial_from_byte_region = tracked_q_parse

def forbidden(*args):
    raise AssertionError('legacy stream-sized integer or scalar ingress was used')

ffi.fmpz_polynomial_deserialize = forbidden
ffi.fmpq_polynomial_deserialize = forbidden
ffi.fmpz_polynomial_set_coefficient = forbidden
ffi.fmpq_polynomial_set_coefficient = forbidden

R = PolynomialRing(ZZ, 'x')
S = PolynomialRing(QQ, 'y')
huge = 2**65537 + 17
denominator = 2**32771 + 1
zvalues = [1, -2, 0, huge, -huge, 7, 0, 0]
qvalues = [QQ(1, 2), QQ(-2, 3), 0, QQ(huge, denominator), QQ(-5, huge), 7, 0]

events.clear()
z = R(zvalues)
assert events == ['region', 'parse-z'], events
assert z.coefficients() == zvalues[:-2]
assert all(region.closed for region in regions)
zvalues[0] = 999
assert z[0] == 1

events.clear()
q = S(qvalues)
assert events == ['region', 'parse-q'], events
assert q.coefficients() == qvalues[:-1]
assert all(region.closed for region in regions)
qvalues[0] = 99
assert q[0] == QQ(1, 2)

# The first pack declines arbitrary values and the ordinary Sage coercion loop
# remains observable and correct before the canonical retry.
class Coercible:
    def __init__(self, value):
        self.value = value
    def lift(self):
        return self.value

events.clear()
coerced = R([Coercible(3), Coercible(-4)])
events.clear()
assert coerced == R([3, -4])
assert events == ['region', 'parse-z'], events

# Fast-path recognition must happen before any user equality method. Sage
# coerces these ZZ values through lift; a misleading or raising comparison
# may not turn a nonzero coefficient into a trailing zero.
class MisleadingZero:
    def __eq__(self, other):
        return True
    def lift(self):
        return 7

class RaisingEquality:
    def __eq__(self, other):
        raise AssertionError('equality was called before coefficient coercion')
    def lift(self):
        return 11

assert R([MisleadingZero()]) == R([7])
assert R([RaisingEquality()]) == R([11])

# QQ currently rejects these arbitrary objects, but it must reject by ordinary
# coercion rather than consulting their hostile equality and silently yielding
# the zero polynomial.
for hostile in [MisleadingZero(), RaisingEquality()]:
    try:
        S([hostile])
    except TypeError:
        pass
    else:
        raise AssertionError('uncoercible QQ coefficient was silently trimmed')

assert loads(dumps(z)) == z
assert loads(dumps(q)) == q
assert all(region.closed for region in regions)
print('exact-polynomial-bulk-construction-ok')
`;

test("public exact polynomial construction selects one generated byte-region parse", () => {
  assert.equal(runSage(publicConstruction), "exact-polynomial-bulk-construction-ok");
});

test("public exact construction source tries checked whole-list packing first", () => {
  const source = readFileSync(join(root, "src/baselib/polynomial.py"), "utf8");
  const start = source.indexOf("    def _from_coefficients(");
  assert.notEqual(start, -1);
  const body = source.slice(start, source.indexOf("\n    def ", start + 8));
  const integerPack = body.indexOf(
    "body = runtime.exact_integer_values_to_packed_bytes(values)",
  );
  const rationalPack = body.indexOf(
    "body = runtime.canonical_rational_values_to_packed_bytes(",
  );
  const integerCoercion = body.indexOf("runtime.integer_bigint(self._base(value))");
  const rationalCoercion = body.indexOf(
    "values = [self._base(value) for value in coefficients]",
  );
  assert.ok(integerPack >= 0 && integerPack < integerCoercion);
  assert.ok(rationalPack >= 0 && rationalPack < rationalCoercion);
});

const portableConstruction = String.raw`
import sagejs._baselib.polynomial as polynomial_module
polynomial_module._generated_flint_resources_available_cache = False
R = PolynomialRing(ZZ, 'x')
S = PolynomialRing(QQ, 'y')
huge = 2**65537 + 17
denominator = 2**32771 + 1
z = R([1, -2, huge, 0])
q = S([QQ(-1, 2), QQ(huge, denominator), 0])
assert z.coefficients() == [1, -2, huge]
assert q.coefficients() == [QQ(-1, 2), QQ(huge, denominator)]
assert not z._has_fmpz_polynomial_resource()
assert not q._has_fmpq_polynomial_resource()
print('exact-polynomial-portable-construction-ok')
`;

test("capability-disabled construction preserves packed exact semantics", () => {
  assert.equal(
    runSage(portableConstruction, { SAGEJS_NATIVE_DISABLE: "1" }),
    "exact-polynomial-portable-construction-ok",
  );
});

test("lazy signed IntegerBuffer ingress stays packed and resource-identical", () => {
  const source = String.raw`
import sagejs.runtime as runtime
import sagejs._baselib.polynomial as polynomial_module

R = PolynomialRing(ZZ, "x")
values = []
for index in range(65):
    magnitude = 2 ** (137 + (index % 7) * 83) + 17 * index + 1
    values.append(-magnitude if index % 2 else magnitude)
values[-1] = 1

capacity = polynomial_module._integer_word_capacity(values)
storage = polynomial_module._FmpzPolynomialResourceStorage(
    runtime.undefined,
    runtime.integer_buffer(values, capacity),
)
lazy = polynomial_module.PolynomialElement(R, storage)
expected = R(values)
expected_bytes = list(expected._packed_exact_polynomial())

lazy._exact_polynomial_resource()
assert lazy == expected
assert list(lazy._packed_exact_polynomial()) == expected_bytes

payload = bytearray(expected_bytes)
damaged_magic = bytearray(expected_bytes)
damaged_magic[0] = 0
damaged_count = bytearray(expected_bytes)
damaged_count[8] = (damaged_count[8] + 1) % 256
for damaged in (payload[:-1], damaged_magic, damaged_count):
    try:
        polynomial_module._exact_polynomial_resource_from_bytes(damaged, False)
    except (ArithmeticError, RuntimeError, TypeError, ValueError):
        pass
    else:
        raise AssertionError("stale or truncated packed polynomial was accepted")

print("exact-polynomial-lazy-resource-ingress-ok")
`;
  assert.equal(runSage(source), "exact-polynomial-lazy-resource-ingress-ok");
});

test("lazy integer resource source has no host-list projection", () => {
  const source = readFileSync(join(root, "src/baselib/polynomial.py"), "utf8");
  const start = source.indexOf("    def _exact_polynomial_resource(self)");
  assert.notEqual(start, -1);
  const body = source.slice(start, source.indexOf("\n    def ", start + 8));
  const integerBranch = body.slice(
    body.indexOf("if self._has_fmpz_polynomial_resource():"),
    body.indexOf("            else:"),
  );
  assert.match(integerBranch, /runtime\.integer_buffer_to_packed_bytes\(/);
  assert.match(integerBranch, /_buffer_length\(/);
  assert.doesNotMatch(integerBranch, /_integer_buffer_values\(/);
  assert.doesNotMatch(integerBranch, /exact_integer_values_to_packed_bytes\(/);
});

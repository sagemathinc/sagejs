#!/usr/bin/env node
"use strict";

const assert = require("node:assert/strict");
const test = require("node:test");
const { createSage } = require("../dist/tools/kernel.js");

test("independent Python authenticates and corrupts fused field analysis", async () => {
  const session = await createSage();
  try {
    const result = await session.evaluate([
      "import sagejs.ffi.flint as flint",
      "from sagejs.number_fields.field_analysis_resource import decode_field_analysis_resource, native_field_analysis",
      "def packed(coefficients, scale=1, bound=1000):",
      "    polynomial = flint.fmpz_polynomial(len(coefficients))",
      "    try:",
      "        for i, value in enumerate(coefficients):",
      "            flint.fmpz_polynomial_set_coefficient(polynomial, i, value)",
      "        flint.fmpz_polynomial_seal(polynomial)",
      "        resource = flint.number_field_analyze_resource(polynomial, scale, bound)",
      "        try:",
      "            return list(resource.copy_bytes())",
      "        finally:",
      "            resource.close()",
      "    finally:",
      "        polynomial.close()",
      "def put_u64(raw, offset, value):",
      "    for i in range(8):",
      "        raw[offset + i] = (value >> (8 * i)) & 255",
      "def integer_regions(raw):",
      "    count = sum(raw[56 + i] << (8 * i) for i in range(8))",
      "    offset = 80",
      "    answer = []",
      "    for unused in range(count):",
      "        header = sum(raw[offset + i] << (8 * i) for i in range(4))",
      "        length = header & 0x7fffffff",
      "        answer.append((offset, offset + 4, offset + 4 + length))",
      "        offset += 4 + length",
      "    return answer",
      "def rejects(raw, polynomial=None, scale=None):",
      "    try:",
      "        decode_field_analysis_resource(raw, expected_polynomial=polynomial, expected_scale=scale)",
      "        return False",
      "    except ValueError:",
      "        return True",
      "complete_raw = packed([-5, 0, 1], 3)",
      "complete = decode_field_analysis_resource(complete_raw, expected_polynomial=[-5, 0, 1], expected_scale=3)",
      "partial_raw = packed([-1022117, 0, 1])",
      "partial = decode_field_analysis_resource(partial_raw)",
      "arbitrary_raw = packed([-18446744073709551629, 0, 1])",
      "arbitrary = decode_field_analysis_resource(arbitrary_raw)",
      "checks = []",
      "checks.append(rejects(complete_raw[:-1]))",
      "tampered = complete_raw[:]",
      "put_u64(tampered, 56, (1 << 64) - 1)",
      "checks.append(rejects(tampered))",
      "tampered = complete_raw + [0]",
      "checks.append(rejects(tampered))",
      "tampered = complete_raw[:]",
      "put_u64(tampered, 40, 99)",
      "checks.append(rejects(tampered))",
      "tampered = complete_raw[:]",
      "regions = integer_regions(tampered)",
      "tampered[regions[3][1]] = tampered[regions[3][1]] + 1",
      "checks.append(rejects(tampered))",
      "tampered = partial_raw[:]",
      "put_u64(tampered, 16, 0)",
      "checks.append(rejects(tampered))",
      "tampered = partial_raw[:]",
      "regions = integer_regions(tampered)",
      "tampered[regions[13][1]] = 0",
      "checks.append(rejects(tampered))",
      "tampered = complete_raw[:]",
      "regions = integer_regions(tampered)",
      "tampered[regions[14][1]] = 2",
      "checks.append(rejects(tampered))",
      "tampered = complete_raw[:]",
      "regions = integer_regions(tampered)",
      "zero_header = regions[7][0]",
      "tampered[zero_header + 3] = 128",
      "checks.append(rejects(tampered))",
      "tampered = complete_raw[:]",
      "regions = integer_regions(tampered)",
      "first_header, first_body, first_end = regions[0]",
      "tampered[first_header] = 2",
      "tampered.insert(first_end, 0)",
      "checks.append(rejects(tampered))",
      "checks.append(rejects(complete_raw, [-6, 0, 1], 3))",
      "checks.append(rejects(complete_raw, [-5, 0, 1], 4))",
      "saved_analysis = flint.number_field_analyze_resource",
      "native_calls = [0]",
      "def counted_analysis(polynomial, scale, bound):",
      "    native_calls[0] = native_calls[0] + 1",
      "    return saved_analysis(polynomial, scale, bound)",
      "flint.number_field_analyze_resource = counted_analysis",
      "try:",
      "    convenient = native_field_analysis([-5, 0, 1], scale=3)",
      "finally:",
      "    flint.number_field_analyze_resource = saved_analysis",
      "checks.append(native_calls == [1] and convenient.candidate_complete and not convenient.certified and convenient.index == 2)",
      "[complete.to_dict(), partial.to_dict(), arbitrary.to_dict(), checks]",
    ].join("\n"));
    assert.equal(result.repr, [
      "[{'schema': 'sagejs.number-fields/native-field-analysis-v1', 'status': 0, 'candidate_complete': True, 'certified': False, 'trial_bound': 1000, 'resolved_components': 2, 'native_primes': 1, 'scale': 3, 'polynomial': [-5, 0, 1], 'components': [{'value': 2, 'exponent': 2, 'state': 'proven-word-prime'}, {'value': 5, 'exponent': 1, 'state': 'proven-word-prime'}], 'basis_numerator': [[1, 1], [0, 2]], 'basis_denominator': 2, 'index': 2, 'equation_discriminant': 20, 'order_discriminant': 5}, ",
      "{'schema': 'sagejs.number-fields/native-field-analysis-v1', 'status': 1, 'candidate_complete': False, 'certified': False, 'trial_bound': 1000, 'resolved_components': 1, 'native_primes': 1, 'scale': 1, 'polynomial': [-1022117, 0, 1], 'components': [{'value': 2, 'exponent': 2, 'state': 'proven-word-prime'}, {'value': 1022117, 'exponent': 1, 'state': 'unresolved'}], 'basis_numerator': [[1, 1], [0, 2]], 'basis_denominator': 2, 'index': 2, 'equation_discriminant': 4088468, 'order_discriminant': 1022117}, ",
      "{'schema': 'sagejs.number-fields/native-field-analysis-v1', 'status': 2, 'candidate_complete': False, 'certified': False, 'trial_bound': 1000, 'resolved_components': 1, 'native_primes': 1, 'scale': 1, 'polynomial': [-18446744073709551629, 0, 1], 'components': [{'value': 2, 'exponent': 2, 'state': 'proven-word-prime'}, {'value': 18446744073709551629, 'exponent': 1, 'state': 'arbitrary-prime-awaiting-proof'}], 'basis_numerator': [[1, 1], [0, 2]], 'basis_denominator': 2, 'index': 2, 'equation_discriminant': 73786976294838206516, 'order_discriminant': 18446744073709551629}, ",
      "[True, True, True, True, True, True, True, True, True, True, True, True, True]]",
    ].join(""));
  } finally {
    await session.close();
  }
});
